import { sql, type Kysely } from "kysely";
import type { SecretsDB } from "../db/schema.js";
import type { OpenBaoTransitClient } from "../openbao-transit.js";

/**
 * Shared service for reading + writing tenant env vars and secrets. Used by:
 *   - The GraphQL resolvers (`vetra-cloud-secrets` subgraph) — the public
 *     surface that the vetra.to Configuration UI talks to.
 *   - The `vetra-cloud-environment` gitops processor — when emitting tenant
 *     values.yaml, it routes env entries through here so secrets land in
 *     the encrypted `tenant_secrets` table (and never in plaintext in the
 *     synced values.yaml).
 *
 * All writes pg_notify('vetra_secrets_changed', tenantId) inside the
 * same transaction so the standalone `vetra-secrets-controller` pod
 * picks up the change and materializes the tenant ConfigMap/Secret.
 */

export const KEY_PATTERN = /^[A-Z][A-Z0-9_]*$/;
export const NOTIFY_CHANNEL = "vetra_secrets_changed";

export class InvalidSecretsKeyError extends Error {
  constructor(key: string) {
    super(
      `Invalid key "${key}": key must match ^[A-Z][A-Z0-9_]*$ (e.g. MY_VAR, API_KEY)`,
    );
    this.name = "InvalidSecretsKeyError";
  }
}

/**
 * Keys reserved for another write path. PH_CONNECT_CONFIG_JSON is owned by the
 * vetra-cloud-environment document model (SET_RUNTIME_CONFIG operation) and is
 * rendered onto the connect pod's env via the gitops processor — it must not be
 * set as a raw env var here (via the resolvers or the processor's env routing).
 */
const RESERVED_KEYS = new Set<string>(["PH_CONNECT_CONFIG_JSON"]);

/** Encrypts a switchboard's workflow secrets; generated once per tenant. */
export const WORKFLOWS_MASTER_KEY = "PH_WORKFLOWS_SECRETS_MASTER_KEY";

/**
 * A Studio's launch secret: binds its agent to its own Studio App (only its
 * sha256 is kept elsewhere). Generated by Vetra at claim and on rotation.
 */
export const STUDIO_LAUNCH_SECRET_KEY = "VETRA_STUDIO_LAUNCH_SECRET";

/**
 * Secrets Vetra generates and owns. The user-facing paths refuse them (set,
 * delete, the gitops routing of document-declared env) and a whole-config
 * replace keeps them. The workflows master key is written only by
 * ensureSecret: replacing it makes the data encrypted under it unreadable.
 */
export const MANAGED_SECRET_KEYS = new Set<string>([
  WORKFLOWS_MASTER_KEY,
  STUDIO_LAUNCH_SECRET_KEY,
]);

/**
 * Managed secrets Vetra itself may overwrite (setManagedSecret, the `managed`
 * entries of replaceTenantConfig). Never the workflows master key.
 */
export const ROTATABLE_MANAGED_KEYS = new Set<string>([STUDIO_LAUNCH_SECRET_KEY]);

/** Managed secrets a tenant purge keeps (data encrypted under them may outlive the env). */
export const PURGE_KEPT_KEYS = new Set<string>([WORKFLOWS_MASTER_KEY]);

export class ManagedSecretKeyError extends Error {
  constructor(key: string) {
    super(
      `"${key}" is generated and managed by Vetra Cloud; it cannot be set or deleted`,
    );
    this.name = "ManagedSecretKeyError";
  }
}

function validateKey(key: string): void {
  if (!KEY_PATTERN.test(key)) {
    throw new InvalidSecretsKeyError(key);
  }
  if (RESERVED_KEYS.has(key)) {
    throw new Error(
      `Reserved key "${key}" cannot be set via setEnvVar; set it through the vetra-cloud-environment document's SET_RUNTIME_CONFIG operation instead`,
    );
  }
  if (MANAGED_SECRET_KEYS.has(key)) throw new ManagedSecretKeyError(key);
}

function assertRotatable(key: string, value: string): void {
  if (!ROTATABLE_MANAGED_KEYS.has(key)) throw new ManagedSecretKeyError(key);
  if (value === "") throw new Error(`Empty value for managed secret "${key}"`);
}

export interface SecretsService {
  /** Plaintext env vars for one tenant, sorted by key. */
  listEnvVars(tenantId: string): Promise<Array<{ key: string; value: string }>>;
  /** Secret KEY names for one tenant (values never returned), sorted. */
  listSecretKeys(tenantId: string): Promise<Array<{ key: string }>>;
  /** Upsert a plaintext env var. Notifies the secrets-controller. */
  setEnvVar(
    tenantId: string,
    key: string,
    value: string,
  ): Promise<{ key: string; value: string }>;
  /** Remove a plaintext env var. Returns true if a row was deleted. */
  deleteEnvVar(tenantId: string, key: string): Promise<boolean>;
  /** Upsert a secret. The value is encrypted via OpenBao transit before storage. */
  setSecret(
    tenantId: string,
    key: string,
    value: string,
  ): Promise<{ key: string }>;
  /**
   * Upsert several secrets for one tenant atomically: all rows + a SINGLE
   * pg_notify in one transaction. The single notify is the load-bearing
   * property — it makes the secrets-controller reconcile the tenant ONCE, so
   * the agent pod gets ONE Reloader bounce instead of one per key. Used by the
   * warm-pool claim to deliver the Anthropic key(s) + ADMINS in a single pod
   * rollout. Keys are validated and values encrypted before the transaction
   * opens, so an invalid key fails the whole batch with nothing written.
   */
  setSecrets(
    tenantId: string,
    entries: Array<{ key: string; value: string }>,
  ): Promise<void>;
  /** Remove a secret. Returns true if a row was deleted. */
  deleteSecret(tenantId: string, key: string): Promise<boolean>;
  /**
   * Write a managed secret only if the tenant has none under this key; never
   * overwrites. Notifies only when it writes. Returns whether it wrote.
   */
  ensureSecret(
    tenantId: string,
    key: string,
    generate: () => string,
  ): Promise<boolean>;
  /**
   * Overwrite one rotatable managed secret (ROTATABLE_MANAGED_KEYS) of a
   * tenant, touching no other key. Notifies the controller.
   */
  setManagedSecret(tenantId: string, key: string, value: string): Promise<void>;
  /**
   * Delete every env var and secret of a tenant (its last environment was
   * deleted). Notifies the controller when rows went, so the tenant's
   * ConfigMap/Secret are emptied if the namespace still exists.
   */
  purgeTenant(tenantId: string): Promise<{ envVars: number; secrets: number }>;
  /**
   * Replace a tenant's whole configuration: every env var and every secret
   * not in `entries` is deleted (managed secrets such as the workflows master
   * key are kept), the entries are written (secrets encrypted first), in one
   * transaction with one notify. Entries the user paths would refuse
   * (invalid, reserved or managed keys) and secrets with an empty value are
   * skipped, as the gitops routing skips them. `managed` secrets (rotatable
   * managed keys only, from Vetra itself) are written in the same
   * transaction. Used by the warm-pool claim.
   */
  replaceTenantConfig(
    tenantId: string,
    entries: Array<{ key: string; value: string; secret: boolean }>,
    managed?: Array<{ key: string; value: string }>,
  ): Promise<void>;
}

/**
 * Delete every env var and secret of one tenant (the workflows master key
 * aside; a launch secret goes too) in one transaction, with one notify when
 * anything went. Idempotent. Namespace-safe: query builder only,
 * so the statements resolve through the schema-bound instance.
 */
export async function purgeTenantRows(
  db: Kysely<SecretsDB>,
  tenantId: string,
): Promise<{ envVars: number; secrets: number }> {
  return db.transaction().execute(async (trx) => {
    const envVars = await trx
      .deleteFrom("tenant_env_vars")
      .where("tenantId", "=", tenantId)
      .executeTakeFirst();
    // The workflows master key stays: workflow secrets encrypted under it
    // live in the tenant's database, which (with its volumes and backups)
    // can outlive the environment; deleting the key would make them
    // unreadable for good. It is generated server-side and can never be set
    // or replaced through a user path, so keeping it gives nobody anything.
    const secrets = await trx
      .deleteFrom("tenant_secrets")
      .where("tenantId", "=", tenantId)
      .where("key", "not in", [...PURGE_KEPT_KEYS])
      .executeTakeFirst();
    const out = {
      envVars: Number(envVars.numDeletedRows),
      secrets: Number(secrets.numDeletedRows),
    };
    if (out.envVars + out.secrets > 0) {
      await sql`SELECT pg_notify(${NOTIFY_CHANNEL}, ${tenantId})`.execute(trx);
    }
    return out;
  });
}

export interface CreateSecretsServiceArgs {
  db: Kysely<SecretsDB>;
  transit: OpenBaoTransitClient;
}

export function createSecretsService({
  db,
  transit,
}: CreateSecretsServiceArgs): SecretsService {
  return {
    async listEnvVars(tenantId) {
      return db
        .selectFrom("tenant_env_vars")
        .select(["key", "value"])
        .where("tenantId", "=", tenantId)
        .orderBy("key", "asc")
        .execute();
    },

    async listSecretKeys(tenantId) {
      return db
        .selectFrom("tenant_secrets")
        .select("key")
        .where("tenantId", "=", tenantId)
        .orderBy("key", "asc")
        .execute();
    },

    async setEnvVar(tenantId, key, value) {
      validateKey(key);
      const now = new Date().toISOString();
      await db.transaction().execute(async (trx) => {
        await trx
          .insertInto("tenant_env_vars")
          .values({ tenantId, key, value, updatedAt: now })
          .onConflict((oc) =>
            oc
              .columns(["tenantId", "key"])
              .doUpdateSet({ value, updatedAt: now }),
          )
          .execute();
        await sql`SELECT pg_notify(${NOTIFY_CHANNEL}, ${tenantId})`.execute(trx);
      });
      return { key, value };
    },

    async deleteEnvVar(tenantId, key) {
      return await db.transaction().execute(async (trx) => {
        const result = await trx
          .deleteFrom("tenant_env_vars")
          .where("tenantId", "=", tenantId)
          .where("key", "=", key)
          .executeTakeFirst();
        const deleted = Number(result.numDeletedRows) > 0;
        if (deleted) {
          await sql`SELECT pg_notify(${NOTIFY_CHANNEL}, ${tenantId})`.execute(
            trx,
          );
        }
        return deleted;
      });
    },

    async setSecret(tenantId, key, value) {
      validateKey(key);
      await transit.ensureTenantKey(tenantId);
      const ciphertext = await transit.encrypt(tenantId, value);
      const now = new Date().toISOString();
      await db.transaction().execute(async (trx) => {
        await trx
          .insertInto("tenant_secrets")
          .values({ tenantId, key, updatedAt: now, ciphertext })
          .onConflict((oc) =>
            oc
              .columns(["tenantId", "key"])
              .doUpdateSet({ updatedAt: now, ciphertext }),
          )
          .execute();
        await sql`SELECT pg_notify(${NOTIFY_CHANNEL}, ${tenantId})`.execute(trx);
      });
      return { key };
    },

    async setSecrets(tenantId, entries) {
      if (entries.length === 0) return;
      // Validate + encrypt BEFORE opening the transaction so a bad key (or a
      // transit failure) aborts the whole batch with nothing written — no
      // partial materialization, no spurious notify.
      for (const e of entries) validateKey(e.key);
      await transit.ensureTenantKey(tenantId);
      const now = new Date().toISOString();
      const rows = await Promise.all(
        entries.map(async (e) => ({
          tenantId,
          key: e.key,
          updatedAt: now,
          ciphertext: await transit.encrypt(tenantId, e.value),
        })),
      );
      await db.transaction().execute(async (trx) => {
        await trx
          .insertInto("tenant_secrets")
          .values(rows)
          .onConflict((oc) =>
            oc.columns(["tenantId", "key"]).doUpdateSet((eb) => ({
              updatedAt: eb.ref("excluded.updatedAt"),
              ciphertext: eb.ref("excluded.ciphertext"),
            })),
          )
          .execute();
        // Exactly one notify for the whole batch → one controller reconcile →
        // one Reloader bounce.
        await sql`SELECT pg_notify(${NOTIFY_CHANNEL}, ${tenantId})`.execute(trx);
      });
    },

    async deleteSecret(tenantId, key) {
      if (MANAGED_SECRET_KEYS.has(key)) throw new ManagedSecretKeyError(key);
      return await db.transaction().execute(async (trx) => {
        const result = await trx
          .deleteFrom("tenant_secrets")
          .where("tenantId", "=", tenantId)
          .where("key", "=", key)
          .executeTakeFirst();
        const deleted = Number(result.numDeletedRows) > 0;
        if (deleted) {
          await sql`SELECT pg_notify(${NOTIFY_CHANNEL}, ${tenantId})`.execute(
            trx,
          );
        }
        return deleted;
      });
    },

    async ensureSecret(tenantId, key, generate) {
      if (!KEY_PATTERN.test(key)) throw new InvalidSecretsKeyError(key);
      const existing = await db
        .selectFrom("tenant_secrets")
        .select("key")
        .where("tenantId", "=", tenantId)
        .where("key", "=", key)
        .executeTakeFirst();
      if (existing) return false;
      await transit.ensureTenantKey(tenantId);
      const ciphertext = await transit.encrypt(tenantId, generate());
      const now = new Date().toISOString();
      return await db.transaction().execute(async (trx) => {
        // A concurrent writer may have inserted since the check above.
        const inserted = await trx
          .insertInto("tenant_secrets")
          .values({ tenantId, key, updatedAt: now, ciphertext })
          .onConflict((oc) => oc.columns(["tenantId", "key"]).doNothing())
          .returning("key")
          .executeTakeFirst();
        if (!inserted) return false;
        await sql`SELECT pg_notify(${NOTIFY_CHANNEL}, ${tenantId})`.execute(trx);
        return true;
      });
    },

    async setManagedSecret(tenantId, key, value) {
      assertRotatable(key, value);
      await transit.ensureTenantKey(tenantId);
      const ciphertext = await transit.encrypt(tenantId, value);
      const now = new Date().toISOString();
      await db.transaction().execute(async (trx) => {
        await trx
          .insertInto("tenant_secrets")
          .values({ tenantId, key, updatedAt: now, ciphertext })
          .onConflict((oc) =>
            oc.columns(["tenantId", "key"]).doUpdateSet({ updatedAt: now, ciphertext }),
          )
          .execute();
        await sql`SELECT pg_notify(${NOTIFY_CHANNEL}, ${tenantId})`.execute(trx);
      });
    },

    async replaceTenantConfig(tenantId, entries, managed = []) {
      for (const m of managed) assertRotatable(m.key, m.value);
      const usable = new Map<string, { value: string; secret: boolean }>();
      for (const e of entries) {
        try {
          validateKey(e.key);
        } catch {
          continue;
        }
        if (e.secret && e.value === "") continue;
        usable.set(e.key, { value: e.value, secret: e.secret });
      }
      const now = new Date().toISOString();
      const plain = [...usable].filter(([, v]) => !v.secret);
      const secret = [
        ...[...usable].filter(([, v]) => v.secret),
        ...managed.map((m): [string, { value: string; secret: boolean }] => [
          m.key,
          { value: m.value, secret: true },
        ]),
      ];
      if (secret.length > 0) await transit.ensureTenantKey(tenantId);
      const secretRows = await Promise.all(
        secret.map(async ([key, v]) => ({
          tenantId,
          key,
          updatedAt: now,
          ciphertext: await transit.encrypt(tenantId, v.value),
        })),
      );
      await db.transaction().execute(async (trx) => {
        await trx.deleteFrom("tenant_env_vars").where("tenantId", "=", tenantId).execute();
        await trx
          .deleteFrom("tenant_secrets")
          .where("tenantId", "=", tenantId)
          .where("key", "not in", [...MANAGED_SECRET_KEYS])
          .execute();
        if (plain.length > 0) {
          await trx
            .insertInto("tenant_env_vars")
            .values(plain.map(([key, v]) => ({ tenantId, key, value: v.value, updatedAt: now })))
            .execute();
        }
        if (secretRows.length > 0) {
          // Managed rows were kept by the delete above: overwrite them.
          await trx
            .insertInto("tenant_secrets")
            .values(secretRows)
            .onConflict((oc) =>
              oc.columns(["tenantId", "key"]).doUpdateSet((eb) => ({
                updatedAt: eb.ref("excluded.updatedAt"),
                ciphertext: eb.ref("excluded.ciphertext"),
              })),
            )
            .execute();
        }
        await sql`SELECT pg_notify(${NOTIFY_CHANNEL}, ${tenantId})`.execute(trx);
      });
    },

    async purgeTenant(tenantId) {
      return purgeTenantRows(db, tenantId);
    },
  };
}
